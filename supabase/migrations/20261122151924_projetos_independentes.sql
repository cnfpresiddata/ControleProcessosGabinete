-- Migração do banco inteiro: separou sispad, jogo_confea e caged. Guardada aqui como registro da mudança no sispad.
-- Cada projeto 100% independente: perfis, log, rótulos e funções no próprio schema.
-- Os nomes usados pelas páginas (meu_perfil, registrar_acesso, historico, valoriza_*) não mudam.

do $mig$
declare
  s text;
  f record;
  d text;
  v_reg text := pg_get_functiondef('auditoria.registrar()'::regprocedure);
  pol record;
  trg record;
  vw record;
  v_opts text;
  v_check text;
begin
  select pg_get_constraintdef(oid) into v_check from pg_constraint where conrelid = 'auditoria.eventos'::regclass and conname = 'eventos_acao_check';

  foreach s in array array['sispad', 'jogo_confea', 'caged'] loop
    -- tabelas próprias
    execute format($q$
      create table %1$I.perfis (
        user_id uuid primary key references auth.users(id) on delete cascade,
        papel text not null check (papel in ('admin','editor','leitor')),
        nome text not null,
        usuario text not null,
        ativo boolean not null default true,
        criado_em timestamptz not null default now()
      );
      insert into %1$I.perfis (user_id, papel, nome, usuario, ativo, criado_em)
        select user_id, papel, nome, usuario, ativo, criado_em from acesso.perfis where projeto = %1$L;
      create table %1$I.eventos (
        id bigint generated by default as identity primary key,
        quando timestamptz not null default now(),
        user_id uuid,
        usuario text not null,
        acao text not null,
        tabela text,
        registro_id text,
        registro text,
        descricao text not null,
        antes jsonb,
        depois jsonb,
        lote bigint,
        constraint eventos_acao_check %2$s
      );
      insert into %1$I.eventos (id, quando, user_id, usuario, acao, tabela, registro_id, registro, descricao, antes, depois, lote)
        select id, quando, user_id, usuario, acao, tabela, registro_id, registro, descricao, antes, depois, lote
        from auditoria.eventos where projeto = %1$L order by id;
      select setval(pg_get_serial_sequence('%1$I.eventos', 'id'), greatest((select max(id) from %1$I.eventos), 1));
      create index eventos_quando_idx on %1$I.eventos (quando desc);
      create index eventos_registro_idx on %1$I.eventos (tabela, registro_id);
      create index eventos_lote_idx on %1$I.eventos (lote) where lote is not null;
      create table %1$I.rotulos (tabela text not null, coluna text not null, rotulo text not null, primary key (tabela, coluna));
      insert into %1$I.rotulos select tabela, coluna, rotulo from auditoria.rotulos where projeto = %1$L;

      create function %1$I.tem_papel(p_papeis text[] default array['admin','editor','leitor'])
      returns boolean language sql stable security definer set search_path = '' as $f$
        select exists (select 1 from %1$I.perfis p where p.user_id = (select auth.uid()) and p.ativo and p.papel = any(p_papeis));
      $f$;
      create function %1$I.nome_usuario() returns text
      language sql stable security definer set search_path = '' as $f$
        select coalesce((select p.nome from %1$I.perfis p where p.user_id = (select auth.uid())),
          case when (select auth.uid()) is null then 'Visitante sem login' else 'Usuário sem perfil' end);
      $f$;

      alter table %1$I.perfis enable row level security;
      alter table %1$I.eventos enable row level security;
      alter table %1$I.rotulos enable row level security;
      create policy le_o_proprio on %1$I.perfis for select to authenticated using (user_id = (select auth.uid()));
      create policy le_equipe on %1$I.eventos for select to authenticated using (%1$I.tem_papel());
      create policy le_equipe on %1$I.rotulos for select to authenticated using (%1$I.tem_papel());
      revoke all on %1$I.perfis, %1$I.eventos, %1$I.rotulos from anon;
      grant select on %1$I.perfis, %1$I.eventos, %1$I.rotulos to authenticated;
      grant all on %1$I.perfis, %1$I.eventos, %1$I.rotulos to service_role;
      revoke execute on function %1$I.tem_papel(text[]), %1$I.nome_usuario() from public;
      grant execute on function %1$I.tem_papel(text[]), %1$I.nome_usuario() to anon, authenticated, service_role;
    $q$, s, v_check);

    -- função de log própria
    d := v_reg;
    d := replace(d, 'FUNCTION auditoria.registrar()', format('FUNCTION %I.registrar()', s));
    d := replace(d, $x$current_setting('auditoria.silenciar', true)$x$, format($x$current_setting('%s.silenciar', true)$x$, s));
    d := replace(d, 'acesso.nome_usuario(v_proj)', format('%I.nome_usuario()', s));
    d := replace(d, 'from auditoria.rotulos r where r.projeto = v_proj and ', format('from %I.rotulos r where ', s));
    d := replace(d, 'insert into auditoria.eventos (projeto, ', format('insert into %I.eventos (', s));
    d := replace(d, 'values (v_proj, ', 'values (');
    if d ~ '(acesso|auditoria)\.' then raise exception 'registrar de %: sobrou referência compartilhada', s; end if;
    execute d;

    -- funções do projeto que usavam acesso ou auditoria
    for f in select p.oid from pg_proc p join pg_namespace n on n.oid = p.pronamespace
             where n.nspname = s and p.prosrc ~ '(acesso|auditoria)\.' and p.proname not in ('registrar') loop
      d := pg_get_functiondef(f.oid);
      d := regexp_replace(d, format($r$acesso\.tem_papel\(\s*'%s'(::text)?\s*,\s*$r$, s), format('%I.tem_papel(', s), 'g');
      d := regexp_replace(d, format($r$acesso\.tem_papel\(\s*'%s'(::text)?\s*\)$r$, s), format('%I.tem_papel()', s), 'g');
      d := regexp_replace(d, format($r$acesso\.nome_usuario\(\s*'%s'(::text)?\s*\)$r$, s), format('%I.nome_usuario()', s), 'g');
      d := regexp_replace(d, format($r$acesso\.perfis\s+p\s+where\s+p\.user_id\s*=\s*\(select auth\.uid\(\)\)\s+and\s+p\.projeto\s*=\s*'%s'\s+and\s+$r$, s), format('%I.perfis p where p.user_id = (select auth.uid()) and ', s), 'g');
      d := regexp_replace(d, $r$insert\s+into\s+auditoria\.eventos\s*\(\s*projeto\s*,\s*$r$, format('insert into %I.eventos (', s), 'g');
      d := regexp_replace(d, format($r$values\s*\(\s*'%s'\s*,\s*$r$, s), 'values (', 'g');
      d := regexp_replace(d, format($r$auditoria\.eventos\s+ev\s+where\s+ev\.projeto\s*=\s*'%s'\s+and\s+$r$, s), format('%I.eventos ev where ', s), 'g');
      d := regexp_replace(d, format($r$auditoria\.eventos\s+where\s+projeto\s*=\s*'%s'\s+and\s+$r$, s), format('%I.eventos where ', s), 'g');
      d := regexp_replace(d, $r$auditoria\.eventos$r$, format('%I.eventos', s), 'g');
      d := replace(d, $x$'auditoria.silenciar'$x$, format($x$'%s.silenciar'$x$, s));
      if d ~ '(acesso|auditoria)\.' then raise exception 'função %: sobrou referência compartilhada: %', f.oid::regprocedure, substring(d from '.{40}(?:acesso|auditoria)\..{40}'); end if;
      execute d;
    end loop;

    -- regras de acesso
    for pol in select * from pg_policies where (schemaname = s or (schemaname = 'storage' and (coalesce(qual,'') || coalesce(with_check,'')) ~ format($r$acesso\.tem_papel\('%s'$r$, s)))
               and (coalesce(qual,'') || coalesce(with_check,'')) ~ 'acesso\.' loop
      execute format('drop policy %I on %I.%I', pol.policyname, pol.schemaname, pol.tablename);
      execute format('create policy %I on %I.%I as %s for %s to %s %s %s', pol.policyname, pol.schemaname, pol.tablename, pol.permissive, pol.cmd,
        (select string_agg(quote_ident(x), ', ') from unnest(pol.roles) x),
        case when pol.qual is not null then 'using (' || regexp_replace(regexp_replace(pol.qual, format($r$acesso\.tem_papel\(\s*'%s'(::text)?\s*,\s*$r$, s), format('%I.tem_papel(', s), 'g'), format($r$acesso\.tem_papel\(\s*'%s'(::text)?\s*\)$r$, s), format('%I.tem_papel()', s), 'g') || ')' else '' end,
        case when pol.with_check is not null then 'with check (' || regexp_replace(regexp_replace(pol.with_check, format($r$acesso\.tem_papel\(\s*'%s'(::text)?\s*,\s*$r$, s), format('%I.tem_papel(', s), 'g'), format($r$acesso\.tem_papel\(\s*'%s'(::text)?\s*\)$r$, s), format('%I.tem_papel()', s), 'g') || ')' else '' end);
    end loop;

    -- gatilhos de log
    for trg in select t.tgname, c.relname, pg_get_triggerdef(t.oid) def from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
               join pg_proc p on p.oid = t.tgfoid join pg_namespace pn on pn.oid = p.pronamespace
               where n.nspname = s and pn.nspname = 'auditoria' and not t.tgisinternal loop
      execute format('drop trigger %I on %I.%I', trg.tgname, s, trg.relname);
      execute replace(trg.def, 'auditoria.registrar(', format('%I.registrar(', s));
    end loop;

    -- visões
    for vw in select c.oid, c.relname, c.reloptions from pg_class c join pg_namespace n on n.oid = c.relnamespace
              where n.nspname = s and c.relkind = 'v' and pg_get_viewdef(c.oid) ~ '(acesso|auditoria)\.' loop
      d := pg_get_viewdef(vw.oid);
      d := regexp_replace(d, format($r$FROM\s+auditoria\.eventos\s+WHERE\s+\(?projeto\s*=\s*'%s'::text\)?$r$, s), format('FROM %I.eventos', s));
      if d ~ '(acesso|auditoria)\.' then raise exception 'visão %.%: sobrou referência compartilhada', s, vw.relname; end if;
      v_opts := case when vw.reloptions is not null then ' with (' || array_to_string(vw.reloptions, ', ') || ')' else '' end;
      execute format('create or replace view %I.%I%s as %s', s, vw.relname, v_opts, rtrim(d, '; '));
    end loop;
  end loop;

  -- nada de fora pode continuar apontando para os schemas compartilhados
  if exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
             where n.nspname not in ('acesso','auditoria','pg_catalog','information_schema') and p.prosrc ~ '(acesso|auditoria)\.(tem_papel|nome_usuario|perfis|projetos|eventos|rotulos|registrar)')
     or exists (select 1 from pg_policies where schemaname not in ('acesso','auditoria') and (coalesce(qual,'') || coalesce(with_check,'')) ~ '(acesso|auditoria)\.')
     or exists (select 1 from pg_views where schemaname not in ('acesso','auditoria','pg_catalog','information_schema') and definition ~ '(acesso|auditoria)\.')
     or exists (select 1 from pg_trigger t join pg_proc p on p.oid = t.tgfoid join pg_namespace pn on pn.oid = p.pronamespace
                join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
                where pn.nspname in ('acesso','auditoria') and n.nspname not in ('acesso','auditoria'))
  then raise exception 'ainda há objetos ligados aos schemas compartilhados';
  end if;

  -- conferência das cópias
  if (select count(*) from auditoria.eventos) <> (select count(*) from sispad.eventos) + (select count(*) from jogo_confea.eventos) + (select count(*) from caged.eventos)
     or (select count(*) from acesso.perfis) <> (select count(*) from sispad.perfis) + (select count(*) from jogo_confea.perfis) + (select count(*) from caged.perfis)
     or (select count(*) from auditoria.rotulos) <> (select count(*) from sispad.rotulos) + (select count(*) from jogo_confea.rotulos) + (select count(*) from caged.rotulos)
  then raise exception 'contagem das cópias não bate';
  end if;
end $mig$;

alter publication supabase_realtime drop table auditoria.eventos;
alter publication supabase_realtime add table sispad.eventos;

drop schema acesso cascade;
drop schema auditoria cascade;

-- cópias antigas do jogo ficam com o jogo
alter schema arquivo rename to jogo_confea_arquivo;
